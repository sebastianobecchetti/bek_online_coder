#!/usr/bin/env bash
# Re-vendors the bek-ts codec source this project bundles, from the sibling
# dev checkout at ../bek-ts. Run this manually whenever bek-ts changes and
# you want this project to pick up the update -- it is NOT run by the build
# or by CI (CI has no access to ../bek-ts; it only ever sees the committed
# vendor/bek-ts snapshot). This script only ever copies files OUT of
# ../bek-ts; it never writes into it.
set -euo pipefail
cd "$(dirname "$0")/.."

SRC=../bek-ts/src
DST=vendor/bek-ts/src
mkdir -p "$DST"

# Only the modules this project actually imports (encode path + types).
# webp.ts and node:fs-touching ply.ts are intentionally NOT vendored: this
# project aliases webp.ts to src/webp-wasm.ts and never uses ply.ts's
# fs-based reader/writer (see src/ply-browser.ts).
FILES="cbor.ts order.ts quantize.ts rvq.ts rangecoder.ts encode.ts container.ts"
for f in $FILES; do
  cp "$SRC/$f" "$DST/$f"
done

# Anello 1 (npm run verify): a manifest of what SHOULD be in vendor/bek-ts/src
# right now, so `npm run verify` can catch drift -- either the vendored
# files getting hand-edited, or this script not being re-run after bek-ts
# changed -- without needing ../bek-ts to be reachable (CI never has it).
MANIFEST=vendor/bek-ts/manifest.json
{
  echo '{'
  echo "  \"_comment\": \"sha256 of each vendored file, regenerated by sync-codec.sh. See scripts/verify-vendor.mjs.\","
  echo "  \"source\": \"$(cd "$SRC" && git rev-parse HEAD 2>/dev/null || echo 'no-git')\","
  echo '  "files": {'
  first=1
  for f in $FILES; do
    [ "$first" -eq 1 ] || echo ','
    first=0
    printf '    "%s": "%s"' "$f" "$(shasum -a 256 "$DST/$f" | cut -d' ' -f1)"
  done
  echo
  echo '  }'
  echo '}'
} > "$MANIFEST"

echo "Synced $(cd "$SRC" && git rev-parse HEAD 2>/dev/null || echo 'no-git') -> $DST (manifest: $MANIFEST)"
